function normalize(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, '');
}

function catalogKey(home: Pick<MasterCatalogHome, 'manufacturer' | 'name'>): string {
  return `${normalize(home.manufacturer)}::${normalize(home.name)}`;
}

export function reconcileCatalogToMasterQuote5(homes: MasterCatalogHome[]): MasterCatalogHome[] {
  const seen = new Set<string>();
  const reconciled: MasterCatalogHome[] = [];

  for (const home of homes) {
    if (MASTER_QUOTE_5_EXCLUDED_MANUFACTURERS.has(home.manufacturer)) continue;
    const key = catalogKey(home);
    if (seen.has(key)) continue;
    seen.add(key);
    const price = MASTER_QUOTE_5_PRICES[key];
    if (!price) continue;
    const [hudBasePrice, estFactoryCost, msrp, ehsPrice] = price;
    reconciled.push({ ...home, hudBasePrice, estFactoryCost, msrp, ehsPrice, startingPrice: ehsPrice });
  }
  return reconciled;
}

