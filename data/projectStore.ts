export function getStoredProjects(): GhlProject[] {
  if (typeof window === 'undefined') return INITIAL_GHL_PROJECTS;
  try {
    const raw = localStorage.getItem('ehs_ghl_projects');
    if (!raw) {
      localStorage.setItem('ehs_ghl_projects', JSON.stringify(INITIAL_GHL_PROJECTS));
      return INITIAL_GHL_PROJECTS;
    }
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : INITIAL_GHL_PROJECTS;
  } catch {
    return INITIAL_GHL_PROJECTS;
  }
}

export function saveProjectsToStore(projects: GhlProject[]) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem('ehs_ghl_projects', JSON.stringify(projects));
    window.dispatchEvent(new Event('storage'));
    window.dispatchEvent(new CustomEvent('ehs_projects_updated'));
  } catch (err) {
    console.error('Failed to save projects to store:', err);
  }
}

export function updateProjectStage(projectId: string, newStage: ProjectStage) {
  const projects = getStoredProjects();
  const index = projects.findIndex((p) => p.id === projectId);
  if (index >= 0) {
    const stagePctMap: Record<ProjectStage, number> = {
      LEAD_QUALIFIED: 10,
      PERMITTING: 25,
      SITE_PREP: 40,
      FACTORY_BUILD: 55,
      TRANSPORT_SET: 70,
      UTILITIES_HOOKUP: 85,
      FINAL_INSPECTION: 95,
      COMPLETED: 100
    };
    projects[index] = {
      ...projects[index],
      stage: newStage,
      progressPct: stagePctMap[newStage] || projects[index].progressPct,
      updatedAt: new Date().toISOString()
    };
    saveProjectsToStore(projects);
  }
}
